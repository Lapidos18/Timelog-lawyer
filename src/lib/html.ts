/**
 * Экранирование текста, который подставляется в HTML печатных документов
 * (акты, отчёты, акт сверки — они собираются строкой и открываются через
 * document.write для печати).
 *
 * Без этого символы «<» и «>» в описании работы браузер принимает за разметку
 * и молча выбрасывает кусок текста из готового документа. Например,
 * «Расчёт неустойки <1/300 ставки>» напечатается как «Расчёт неустойки»
 * — и заметить это можно уже только по вопросу доверителя.
 *
 * Применять к КАЖДОМУ значению, введённому пользователем: описания, имена
 * клиентов, названия дел, номера актов и договоров. Числа и даты, полученные
 * из formatMoney/format, экранировать не нужно, но и вреда от этого нет.
 */
export function escapeHtml(value: unknown): string {
  if (value === null || value === undefined) return ''
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
}
