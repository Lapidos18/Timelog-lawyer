import { useEffect, useState } from 'react'

/**
 * false — на сервере и при первой отрисовке в браузере, true — сразу после неё.
 *
 * Зачем. Страницы раздела собираются заранее, при выпуске версии, и лежат на
 * сервере готовыми. Всё, что в них зависит от «сегодня» (число в заголовке
 * Журнала, месяц на Обзоре, границы периода в фильтрах), навсегда остаётся
 * таким, каким было в день выпуска. Браузер при загрузке считает настоящую дату,
 * видит расхождение и выдаёт ошибку React №418, после чего выбрасывает готовую
 * страницу и рисует её заново. Чтобы расхождения не было, значения, зависящие
 * от даты, показываются только когда `useMounted()` вернул true.
 *
 * Не заменять на `suppressHydrationWarning`: тот только прячет ошибку, а на
 * экране остаётся дата выпуска.
 */
export function useMounted(): boolean {
  const [mounted, setMounted] = useState(false)
  useEffect(() => { setMounted(true) }, [])
  return mounted
}
