-- 014. Ссылка на папку дела в Google Диске
--
-- Документы по делам лежат на Google Диске в папке «Проекты», по подпапке
-- на доверителя или дело. Ссылка в карточке дела открывает эту папку
-- одним нажатием, без поиска по Диску.
--
-- Это просто текстовое поле со ссылкой: приложение к Google не подключается
-- и доступа к Диску не получает. Папка откроется, только если вы вошли
-- в свой Google-аккаунт в том же браузере.

alter table matters add column if not exists drive_folder_url text;
