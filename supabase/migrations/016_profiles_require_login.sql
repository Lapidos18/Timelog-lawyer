-- 016. Профиль виден только после входа
--
-- Зачем. В миграции 001 у profiles стояло правило `for select using (true)`.
-- «true» — это без условий вообще, то есть и для посетителя, который не
-- входил в приложение. Проверено запросом к базе: строка профиля (ФИО, роль,
-- ставка) отдавалась по открытому ключу без пароля. Остальные таблицы
-- закрыты правильно — они требуют `auth.role() = 'authenticated'` и без
-- входа отдают пустой список.
--
-- Правило с `true` задумывалось как «сотрудники видят друг друга», чтобы в
-- списке исполнителей было имя помощника. Условие входа этой задаче не мешает.

drop policy if exists "Все пользователи видят коллег" on profiles;

create policy "Вошедшие видят профили"
  on profiles for select
  using (auth.role() = 'authenticated');

-- Правило «Пользователь видит свой профиль» (001) остаётся: правила
-- складываются по «или», и свой профиль виден в любом случае.
