/**
 * Цвета заданы не значениями, а ссылками на CSS-переменные.
 *
 * Так светлая тема включается одной строкой в globals.css: классы вроде
 * `bg-navy-950` или `text-navy-100` остаются на своих местах во всех
 * разделах, меняется только то, что за ними стоит. Иначе пришлось бы
 * переписать несколько сотен классов вручную и что-нибудь пропустить.
 *
 * Формат `rgb(var(--x) / <alpha-value>)` обязателен: без него перестали бы
 * работать полупрозрачные варианты — `bg-navy-800/50`, `border-gold-800/40`
 * и подобные, а их в приложении много.
 *
 * Смысл ступеней сохранён в обеих темах: navy-950 — фон страницы,
 * navy-900 — карточка, navy-100 — основной текст. В светлой теме шкала
 * перевёрнута, поэтому 950 становится белым, а 100 — почти чёрным.
 */
const scale = (name, steps) =>
  Object.fromEntries(steps.map(s => [s, `rgb(var(--${name}-${s}) / <alpha-value>)`]))

/** @type {import('tailwindcss').Config} */
module.exports = {
  content: [
    './src/pages/**/*.{js,ts,jsx,tsx,mdx}',
    './src/components/**/*.{js,ts,jsx,tsx,mdx}',
    './src/app/**/*.{js,ts,jsx,tsx,mdx}',
  ],
  theme: {
    extend: {
      colors: {
        navy: scale('navy', [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950]),
        gold: scale('gold', [50, 100, 200, 300, 400, 500, 600, 700, 800, 900]),
        // Смысловые цвета: зелёный — получено, красный — долг, янтарный —
        // требует внимания. На белом фоне те же оттенки нечитаемы, поэтому
        // они тоже переопределяются. Перечислены только используемые ступени —
        // остальные Tailwind оставляет своими.
        emerald: scale('ok', [400, 800, 900]),
        red:     scale('bad', [300, 400, 500, 900, 950]),
        amber:   scale('warn', [300, 400, 500, 800, 900, 950]),
        ink: '#1a1a2e',
      },
      fontFamily: {
        sans: ['Inter', 'system-ui', 'sans-serif'],
      },
    },
  },
  plugins: [],
}
